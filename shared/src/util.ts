// Pure value helpers shared by server and web. No I/O, no DOM.

export const RAW_MAX = 16383;

export function clamp(v: number, min: number, max: number): number {
  if (Number.isNaN(v)) return min;
  return v < min ? min : v > max ? max : v;
}

export const clamp01 = (v: number): number => clamp(v, 0, 1);

/** 0..1 -> 0..16383 (SimConnect "position" events such as THROTTLE1_SET). */
export function toRaw16383(v01: number): number {
  return Math.round(clamp01(v01) * RAW_MAX);
}

export function fromRaw16383(raw: number): number {
  return clamp01(raw / RAW_MAX);
}

/** -1..1 -> -16383..16383 (e.g. ELEVATOR_TRIM_SET). */
export function toSigned16383(v: number): number {
  return Math.round(clamp(v, -1, 1) * RAW_MAX);
}

/** Percent (0..100) as reported by "percent" SimVars -> 0..1. */
export function percentToUnit(p: number): number {
  return clamp01(p / 100);
}

export function snapToStep(v: number, step: number, min = 0): number {
  if (step <= 0) return v;
  return min + Math.round((v - min) / step) * step;
}

export function wrap360(deg: number): number {
  const d = deg % 360;
  return d < 0 ? d + 360 : d;
}

/** Encode a 4 digit octal transponder code (e.g. 1200) as BCO16 (0x1200). */
export function encodeBco16(code: number): number {
  const s = String(Math.trunc(code)).padStart(4, '0').slice(-4);
  return parseInt(s, 16);
}

/** Decode a BCO16 value (as read from the "bco16" unit) back to the decimal digits. */
export function decodeBco16(raw: number): number {
  const s = (Math.trunc(raw) & 0xffff).toString(16).padStart(4, '0');
  return parseInt(s, 10);
}

export function isValidSquawk(code: number): boolean {
  return Number.isInteger(code) && code >= 0 && code <= 7777 && /^[0-7]{1,4}$/.test(String(code));
}

export const COM_RANGE_HZ = { min: 118_000_000, max: 136_990_000, step: 25_000 } as const;
export const NAV_RANGE_HZ = { min: 108_000_000, max: 117_950_000, step: 50_000 } as const;

export function hzToMhzString(hz: number, decimals = 3): string {
  return (hz / 1_000_000).toFixed(decimals);
}

/**
 * Snap a frequency to the channel raster. COM uses 25 kHz steps here (8.33 kHz channel
 * spacing is intentionally not generated by the UI; the sim may still report such values).
 */
export function snapFrequency(hz: number, kind: 'com' | 'nav'): number {
  const r = kind === 'com' ? COM_RANGE_HZ : NAV_RANGE_HZ;
  return clamp(snapToStep(hz, r.step, r.min), r.min, r.max);
}

export function stepFrequency(hz: number, kind: 'com' | 'nav', steps: number, coarse: boolean): number {
  const r = kind === 'com' ? COM_RANGE_HZ : NAV_RANGE_HZ;
  const unit = coarse ? 1_000_000 : r.step;
  // wrap around inside the band, working on channel numbers so the band edge is exact
  const channels = Math.floor((r.max - r.min) / r.step) + 1;
  const idx = Math.round((snapFrequency(hz, kind) - r.min) / r.step) + Math.round((steps * unit) / r.step);
  return r.min + (((idx % channels) + channels) % channels) * r.step;
}
